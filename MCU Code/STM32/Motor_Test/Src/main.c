/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_TIM3_Init();
  MX_TIM4_Init();
  MX_ADC1_Init();
  MX_ADC2_Init();
  MX_TIM8_Init();
  /* USER CODE BEGIN 2 */

  /* Start TIM3 PWM channels - Motors 1 and 2 */
  HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_1);
  HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_2);
  HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_3);
  HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_4);

  /* Start TIM4 PWM channels - Motors 3 and 4 */
  HAL_TIM_PWM_Start(&htim4, TIM_CHANNEL_1);
  HAL_TIM_PWM_Start(&htim4, TIM_CHANNEL_2);
  HAL_TIM_PWM_Start(&htim4, TIM_CHANNEL_3);
  HAL_TIM_PWM_Start(&htim4, TIM_CHANNEL_4);

  HAL_TIM_PWM_Start(&htim8, TIM_CHANNEL_1);
  HAL_TIM_PWM_Start(&htim8, TIM_CHANNEL_2);
  HAL_TIM_PWM_Start(&htim8, TIM_CHANNEL_3);
  HAL_TIM_PWM_Start(&htim8, TIM_CHANNEL_4);

  HAL_Delay(1000);


  /* USER CODE END 2 */

  /* Initialize leds */
  BSP_LED_Init(LED2);

  /* Initialize USER push-button, will be used to trigger an interrupt each time it's pressed.*/
  BSP_PB_Init(BUTTON_USER, BUTTON_MODE_EXTI);

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {

	  /* Start ADC conversion */
	  HAL_ADC_Start(&hadc1);

	  /* Wait for conversion */
	  HAL_ADC_PollForConversion(&hadc1, HAL_MAX_DELAY);

	  /* Read ADC value: 0 to 4095 */
	  adc_value = HAL_ADC_GetValue(&hadc1);

	  /* Convert 0...4095 into 0...500 */
	  pwm_value = (adc_value * 500) / 4095;


	  /* MOTOR 1 */
	  __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_1, pwm_value);
	  __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_2, 0);

	  /* MOTOR 2 */
	  __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_3, pwm_value);
	  __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_4, 0);

	  /* MOTOR 3 */
	  __HAL_TIM_SET_COMPARE(&htim4, TIM_CHANNEL_1, pwm_value);
	  __HAL_TIM_SET_COMPARE(&htim4, TIM_CHANNEL_2, 0);

	  /* MOTOR 4 */
	  __HAL_TIM_SET_COMPARE(&htim4, TIM_CHANNEL_3, pwm_value);
	  __HAL_TIM_SET_COMPARE(&htim4, TIM_CHANNEL_4, 0);

	  /* Read servo potentiometer */
	  HAL_ADC_Start(&hadc2);

	  HAL_ADC_PollForConversion(&hadc2, HAL_MAX_DELAY);

	  servo_adc = HAL_ADC_GetValue(&hadc2);

	  HAL_ADC_Stop(&hadc2);

	  servo_pulse = 1000 + ((servo_adc * 1000) / 4095);

	  __HAL_TIM_SET_COMPARE(&htim8, TIM_CHANNEL_1, servo_pulse);
	  __HAL_TIM_SET_COMPARE(&htim8, TIM_CHANNEL_2, servo_pulse);
	  __HAL_TIM_SET_COMPARE(&htim8, TIM_CHANNEL_3, servo_pulse);
	  __HAL_TIM_SET_COMPARE(&htim8, TIM_CHANNEL_4, servo_pulse);


	  HAL_Delay(10);

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

